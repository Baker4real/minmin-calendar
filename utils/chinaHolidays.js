function getPublishedHoliday(dateStr) {
  const holiday = PUBLISHED_HOLIDAY_RANGES.find(item => dateStr >= item.start && dateStr <= item.end)
  if (!holiday) return null
  return {
    name: holiday.name,
    isOffDay: holiday.isOffDay
  }
}

function hasPublishedHolidayYear(year) {
  return year >= PUBLISHED_HOLIDAY_START_YEAR && year <= PUBLISHED_HOLIDAY_END_YEAR
}

